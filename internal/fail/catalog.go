// Codes перечисляет все объявленные коды. Нужен проверке полноты: у каждого
// кода обязан быть текст, у каждого текста — код.
func Codes() []Kind {
	out := make([]Kind, 0, len(catalog))
	for k := range catalog {
		out = append(out, k)
	}
	return out
}
