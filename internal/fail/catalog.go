package fail

// Каталог ошибок — единственное место, где живут коды, тексты и ответы HTTP.
//
// Как добавить ошибку: объявить код константой и внести запись в catalog.
// Больше нигде ничего править не нужно — ни в обработчиках, ни в интерфейсе.
//
// Как писать текст (§ 12 ТЗ):
//
//	Т-1  назвать причину и следующее действие;
//	Т-2  причину, зависящую от состояния, не подменять общей формулировкой —
//	     такие тексты содержат места для подстановки значений;
//	Т-3  обещание давать только исполнимое;
//	И-7  причина действительная, а не предполагаемая.
//
// Коды ответа берутся из § 8.1 и означают ровно следующее:
//
//	400  запрос не разобран или значение недопустимо;
//	404  сущности нет;
//	409  устаревшая версия либо требуется подтверждение (Ф-8.3);
//	422  операция запрещена по существу — повторять нечего;
//	429  слишком часто;
//	503  ядро не отвечает либо панель ещё не готова.

type record struct {
	message string // текст на русском; %s и %d — места подстановки
	status  int    // код ответа HTTP
}

// Коды ошибок. Сгруппированы по предмету, а не по коду ответа: искать их
// приходится по смыслу происходящего.
const (
	// общие
	Internal             Kind = "internal"
	BadRequest           Kind = "bad_request"
	NotFound             Kind = "not_found"
	TooOften             Kind = "too_often"
	BodyTooBig           Kind = "body_too_big"
	StaleVersion         Kind = "stale_version"
	ConfirmationRequired Kind = "confirmation_required"

	// источники и разбор
	SourceUnreachable Kind = "source_unreachable"
	SourceDuplicate   Kind = "source_duplicate"
	SourceTooBig      Kind = "source_too_big"
	LinkUnparsable    Kind = "link_unparsable"
	SchemeNotAllowed  Kind = "scheme_not_allowed"
	AddressNotAllowed Kind = "address_not_allowed"
	TooManyRedirects  Kind = "too_many_redirects"

	// группы и состав
	GroupLimitExceeded Kind = "group_limit_exceeded"
	CoreLimitExceeded  Kind = "core_limit_exceeded"
	PinnedLimitReached Kind = "pinned_limit_reached"
	ManualModeOnly     Kind = "manual_mode_only"
	MembersConflict    Kind = "members_conflict"

	// интерфейсы
	InterfaceNameTaken Kind = "interface_name_taken"
	SubnetOverlap      Kind = "subnet_overlap"

	// ядро и хранилище
	CoreNotResponding Kind = "core_not_responding"
	CoreConfigInvalid Kind = "core_config_invalid"
	CoreRestartFailed Kind = "core_restart_failed"
	FlashFull         Kind = "flash_full"
	FlashFailed       Kind = "flash_failed"
	DataFormatNewer   Kind = "data_format_newer"
)

