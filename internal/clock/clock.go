// Пакет clock — единственный источник времени в программе.
//
// Зачем отдельный пакет. На роутере нет часов реального времени: после
// перезагрузки календарная дата неверна, пока не пройдёт синхронизация, а она
// зависит от канала, который поднимает сама панель (Н-5.6). Поэтому всё
// поведение системы — сроки годности результатов, интервалы опроса, ожидание
// при переключении, страховочные сроки — считается по времени работы системы и
// не зависит от перевода часов.
//
// Отсюда два разных понятия времени, и они не смешиваются:
//
//	Moment    момент по монотонным часам. Годится для «сколько прошло».
//	          Сравнивать можно только моменты одного запуска панели.
//	Calendar  календарное время. Годится только чтобы показать человеку и
//	          чтобы планировать обновление подписок (Н-5.7).
//
// Правило: в логике панели используется Moment. Calendar появляется ровно
// в двух местах — показ пользователю и плановое обновление подписок. Прямой
// вызов time.Now() вне этого пакета запрещён и проверяется тестом.
package clock

import "time"

// Moment — точка на монотонной шкале: время с запуска панели.
//
// Отдельный тип, а не time.Time, именно чтобы монотонное и календарное время
// нельзя было перепутать по невнимательности: компилятор не даст сложить одно
// с другим.
type Moment time.Duration

// Age — сколько прошло от момента m до now.
//
// Отрицательного возраста не бывает: момент из будущего означает ошибку
// вызывающего, и мы возвращаем ноль, а не отрицательную длительность, которая
// потом тихо превратится в «результат свежий».
func (m Moment) Age(now Moment) time.Duration {
	if now <= m {
		return 0
	}
	return time.Duration(now - m)
}

// Before сообщает, наступил ли момент m раньше другого.
func (m Moment) Before(other Moment) bool { return m < other }

// Add сдвигает момент вперёд на длительность: срок, который наступит потом.
func (m Moment) Add(d time.Duration) Moment { return m + Moment(d) }

// Zero — момент, которого не было. Означает «никогда»: нода ещё не измерялась,
// подписка ещё не обновлялась. Возраст такого момента спрашивать бессмысленно,
// сначала проверяют IsZero.
const Zero Moment = 0

// IsZero сообщает, что события не было вовсе.
func (m Moment) IsZero() bool { return m == Zero }

// Clock — часы, которые получает всякий, кому нужно знать время.
//
// Интерфейс, а не функция, по одной причине: в опытах и тестах время должно
// двигаться по команде, а не само. Тогда проверка «результат протух через
// минуту» занимает микросекунды и не зависит от загрузки машины.
type Clock interface {
	// Now — текущий момент по монотонной шкале.
	Now() Moment
	// Calendar — календарное время. Только для показа человеку и планирования
	// обновления подписок (Н-5.7). Второе значение — правдоподобна ли дата:
	// пока часы не синхронизированы, показывать её нельзя.
	Calendar() (time.Time, bool)
	// Sleep — ожидание. Живёт здесь же, потому что в опытах оно тоже обязано
	// быть управляемым: иначе проверка часового интервала занимает час.
	Sleep(d time.Duration)
	// After — канал, срабатывающий через d. Нужен там, где ожидание идёт
	// вместе с другими событиями в select.
	After(d time.Duration) <-chan time.Time
}

// System — настоящие часы поверх стандартной библиотеки.
type System struct {
	start time.Time // момент запуска; от него отсчитывается монотонная шкала
	// Порог правдоподобия календарной даты. Часы роутера до синхронизации
	// показывают дату сборки прошивки или начало эпохи — заведомо прошлое.
	// Всё, что раньше этого порога, календарным временем не считается.
	epoch time.Time
}

// NewSystem заводит настоящие часы. Момент вызова становится нулём монотонной
// шкалы: панель отсчитывает время от собственного запуска.
func NewSystem() *System {
	return &System{
		start: time.Now(),
		// 2025-01-01: раньше этой даты панели не существовало, значит такая
		// дата на роутере означает несинхронизированные часы, а не прошлое.
		epoch: time.Date(2025, 1, 1, 0, 0, 0, 0, time.UTC),
	}
}

// Now возвращает время, прошедшее с запуска панели.
//
// Стандартная библиотека хранит в time.Time монотонную составляющую и
// использует её при вычитании — поэтому перевод часов на этот результат не
// влияет.
func (s *System) Now() Moment { return Moment(time.Since(s.start)) }

// Calendar возвращает календарное время и признак его правдоподобности.
func (s *System) Calendar() (time.Time, bool) {
	now := time.Now()
	return now, now.After(s.epoch)
}

// Sleep ожидает указанную длительность.
func (s *System) Sleep(d time.Duration) { time.Sleep(d) }

// After возвращает канал, срабатывающий через d.
func (s *System) After(d time.Duration) <-chan time.Time { return time.After(d) }
