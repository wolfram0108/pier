package event

// Каталог видов событий — § 8.3 ТЗ, одна запись на вид.
//
// Как добавить событие: константа вида, запись в kinds с составом полей и
// поводом. Больше нигде — интерфейс узнаёт состав отсюда же, из проверки
// полноты.
//
// Правило состава: событие сообщает, что́ изменилось, и несёт ровно столько,
// сколько нужно, чтобы обновить показанное без запроса. Всё, что нужно листать,
// потоком не передаётся.

// Kind — вид события. Имя уходит в поле event потока и не меняется между
// версиями: по нему клиент разбирает поток.
type Kind string

const (
	// Core — сменилось состояние ядра, и только при смене (Ф-8.5).
	// Отражает ответ управляющего интерфейса, и только его (Ф-7.16).
	Core Kind = "core"
	// Speed — общая скорость через ядро, по мере поступления от ядра.
	Speed Kind = "speed"
	// Budget — изменилось число нод в ядре.
	Budget Kind = "budget"
	// Node — нода сменила состояние либо получила новый замер.
	Node Kind = "node"
	// Probe — сдвинулся ход работы с обозримым концом.
	Probe Kind = "probe"
	// Group — сменился состав, активная нода или аварийное состояние.
	Group Kind = "group"
	// Interface — интерфейс появился, исчез или сменил состояние.
	Interface Kind = "interface"
	// Source — подписка обновилась, счётчики изменились.
	Source Kind = "source"
	// Task — длительная операция сменила состояние (Ф-8.6).
	Task Kind = "task"
	// Settings — настройки изменены, в том числе другим клиентом (Ф-8.9).
	Settings Kind = "settings"
	// Resync — «перечитай состояние заново». Панель не хранит пропущенные
	// события: ни после обрыва потока, ни после переполнения буфера (§ 8.3).
	Resync Kind = "resync"
)

type kindSpec struct {
	fields []string // состав полей события
	when   string   // повод: когда событие возникает
}

var kinds = map[Kind]kindSpec{
	Core:      {[]string{"responding"}, "сменилось состояние ядра — и только при смене"},
	Speed:     {[]string{"up", "down"}, "по мере поступления от ядра"},
	Budget:    {[]string{"used", "limit"}, "изменилось число нод в ядре"},
	Node:      {[]string{"fingerprint", "state", "delay", "age"}, "нода сменила состояние либо получила новый замер"},
	Probe:     {[]string{"source_id", "done", "total"}, "сдвинулся ход работы с обозримым концом"},
	Group:     {[]string{"group_id", "alarm", "active", "used"}, "сменился состав, активная нода или аварийное состояние"},
	Interface: {[]string{"interface_id", "up"}, "интерфейс появился, исчез или сменил состояние"},
	Source:    {[]string{"source_id", "counters"}, "подписка обновилась, счётчики изменились"},
	Task:      {[]string{"id", "state", "error"}, "длительная операция сменила состояние"},
	Settings:  {[]string{"version"}, "настройки изменены, в том числе другим клиентом"},
	Resync:    {nil, "клиент отстал или переподключился: состояние нужно перечитать"},
}

// Kinds перечисляет все объявленные виды.
func Kinds() []Kind {
	out := make([]Kind, 0, len(kinds))
	for k := range kinds {
		out = append(out, k)
	}
	return out
}

// Fields возвращает состав полей вида: по нему проверяется, что событие
// отправлено полным, а не с половиной полей.
func Fields(k Kind) ([]string, bool) {
	spec, ok := kinds[k]
	return spec.fields, ok
}
